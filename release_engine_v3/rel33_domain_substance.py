"""REL3.3 — Domain Isolation Contract substance registries (non-cyber).

Deterministic per-domain section substance for data / ai / dt / erm / global
strategy documents. These registries are the ONLY allowed source of baseline
gap / pillar / governance / traceability / roadmap / KPI / SO content for
non-cyber domains. Cyber substance lives in the legacy cyber registries and
must never be injected outside the cyber domain.

Fail-closed principle: a blank/unresolvable domain never falls back to any
registry here or to the cyber registries — callers must raise
``rel33_substance_domain_missing``.
"""

from __future__ import annotations

from typing import Dict, Tuple

REL33_SUBSTANCE_DOMAINS: Tuple[str, ...] = (
    'cyber', 'data', 'ai', 'dt', 'erm', 'global',
)


def require_rel33_substance_domain(domain: str, what: str = 'substance') -> str:
    """Normalize a domain code; blank/unknown fails closed (never cyber)."""
    from release_engine_v3.domain_codes import normalize_domain_code
    code = normalize_domain_code(str(domain or ''), default='')
    if not code:
        raise ValueError(f'rel33_substance_domain_missing:{what}')
    if code not in REL33_SUBSTANCE_DOMAINS:
        raise ValueError(f'rel33_substance_domain_missing:{what}:{code}')
    return code


